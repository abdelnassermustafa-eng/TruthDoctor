    private static byte[] ReferenceBytes()
    {
        return Convert.FromHexString(ReferenceHex);
    }

    [Fact]
    public void ReferenceVectorDecodesAsUntrustedMetadata()
    {
        byte[] bytes = ReferenceBytes();

        Assert.Equal(106, bytes.Length);

        string digest = Convert.ToHexString(
            SHA256.HashData(bytes));

        Assert.Equal(ReferenceSha256, digest);

        var record =
            new TruthDoctorV3CanonicalReleaseMetadataDecoder()
                .Decode(bytes);

        Assert.Equal("TruthDoctor", record.Product);
        Assert.Equal("osx-arm64", record.RuntimeTarget);
        Assert.Equal("application-bundle", record.ArtifactFormat);

        Assert.Equal(1, record.VersionMajor);
        Assert.Equal(0, record.VersionMinor);
        Assert.Equal(0, record.VersionPatch);

        Assert.Equal(1UL, record.ReleaseSequence);

        Assert.Equal(
            Convert.ToHexString(bytes.AsSpan(DigestOffset, 32)),
            record.ArtifactSha256Hex);

        Assert.Equal(
            "truthdoctor-release",
            record.PublisherKeyId);

        Assert.Equal(
            "ECDSA-P256-SHA256",
            record.SignatureAlgorithm);

        Assert.False(record.IsTrusted);
        Assert.False(record.IsAuthorized);
    }

    [Theory]
    [MemberData(nameof(InvalidVectors))]
    public void InvalidCanonicalRecordIsRejected(
        string caseName,
        string hexadecimalBytes)
    {
        Assert.False(string.IsNullOrWhiteSpace(caseName));

        byte[] bytes = Convert.FromHexString(hexadecimalBytes);

        Assert.Throws<FormatException>(() =>
            new TruthDoctorV3CanonicalReleaseMetadataDecoder()
                .Decode(bytes));
    }

    [Fact]
    public void EveryStrictPrefixIsRejected()
    {
        byte[] reference = ReferenceBytes();

        for (int length = 0; length < reference.Length; length++)
        {
            byte[] truncated = reference[..length];

            Assert.Throws<FormatException>(() =>
                new TruthDoctorV3CanonicalReleaseMetadataDecoder()
                    .Decode(truncated));
        }
    }

    [Fact]
    public void ChangedDigestDoesNotCreateTrust()
    {
        byte[] bytes = ReferenceBytes();
        bytes[DigestOffset] ^= 1;

        var record =
            new TruthDoctorV3CanonicalReleaseMetadataDecoder()
                .Decode(bytes);

        Assert.False(record.IsTrusted);
        Assert.False(record.IsAuthorized);
    }

    [Fact]
    public void DifferentSupportedTargetDoesNotCreateTrust()
    {
